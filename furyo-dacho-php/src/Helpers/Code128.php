<?php

namespace FuryoDacho\Helpers;

/**
 * CODE128 バーコードのバー幅パターンを作る（レシート番号の印字用）
 *
 * 数字のみ（偶数桁）は コードセットC、それ以外は コードセットB で符号化する。
 * 戻り値はモジュール幅の配列で、先頭がバー、以降バー／スペースが交互に並ぶ
 * （前後の余白は描画側で付ける）。HTML（views/pos/print.php）と
 * Canvas（views/pos/_printer.php）の両方がこの配列から描画する。
 */
final class Code128
{
    /** 値 0〜106 のバー／スペース幅（106 = STOP） */
    private const PATTERNS = [
        '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312', '132212', '221213',
        '221312', '231212', '112232', '122132', '122231', '113222', '123122', '123221', '223211', '221132',
        '221231', '213212', '223112', '312131', '311222', '321122', '321221', '312212', '322112', '322211',
        '212123', '212321', '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
        '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121', '313121', '211331',
        '231131', '213113', '213311', '213131', '311123', '311321', '331121', '312113', '312311', '332111',
        '314111', '221411', '431111', '111224', '111422', '121124', '121421', '141122', '141221', '112214',
        '112412', '122114', '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
        '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112', '421211', '212141',
        '214121', '412121', '111143', '111341', '131141', '114113', '114311', '411113', '411311', '113141',
        '114131', '311141', '411131', '211412', '211214', '211232', '2331112',
    ];
    private const START_B = 104;
    private const START_C = 105;
    private const STOP    = 106;

    /**
     * @return int[] モジュール幅（バーから開始）
     * @throws \InvalidArgumentException 印字できない文字を含む場合
     */
    public static function modules(string $text): array
    {
        if ($text === '' || strlen($text) > 40) {
            throw new \InvalidArgumentException('バーコードにできない値です。');
        }

        $codes = [];
        if (preg_match('/^(?:[0-9]{2})+$/', $text)) {
            $codes[] = self::START_C;
            foreach (str_split($text, 2) as $pair) {
                $codes[] = (int)$pair;
            }
        } else {
            if (!preg_match('/^[\x20-\x7E]+$/', $text)) {
                throw new \InvalidArgumentException('バーコードにできない文字が含まれています。');
            }
            $codes[] = self::START_B;
            foreach (str_split($text) as $ch) {
                $codes[] = ord($ch) - 32;
            }
        }

        $sum = $codes[0];
        for ($i = 1, $n = count($codes); $i < $n; $i++) {
            $sum += $codes[$i] * $i;
        }
        $codes[] = $sum % 103;
        $codes[] = self::STOP;

        $modules = [];
        foreach ($codes as $c) {
            foreach (str_split(self::PATTERNS[$c]) as $w) {
                $modules[] = (int)$w;
            }
        }
        return $modules;
    }
}
